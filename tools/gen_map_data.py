"""The zone -> map table the Battle HUD draws behind its radar (host/addons/lua/mapdata.lua).

A zone's map is the game's own map DAT (ROM/17, ROM/18, ROM/283-285, ...), the same image the
in-game map screen and the Minimap plugin show.  Two facts are needed to place it:

  * which DAT holds the zone's map, and
  * the map's placement: scale, offsetX, offsetY, from which a world position becomes a texel.

The DAT ids come from the Minimap plugin's own table (the `dat` values in its embedded maps.json:
the file id is what the game's VTABLE/FTABLE resolves to the map DAT).  The placement values come
from the community map data published with FFXI Atlas (data/zonesWithMaps.json); they are facts
about the game's zones, not artwork.  Both are recorded in THIRD_PARTY_NOTICES.md.

  python3 tools/gen_map_data.py --maps minimap_maps.json --atlas zonesWithMaps.json \
      [--zones zones.json] [--out host/addons/lua/mapdata.lua]

The Minimap table is the JSON object embedded in the plugin's Minimap.dll (the last JSON blob in
the binary); the Atlas files are data/zonesWithMaps.json and data/zones.json from its repository.

Only the first floor of a zone is used: a dungeon with several maps gets its lowest floor (the
entrance in most cases).  The HUD falls back to the plain camp radar when a zone has no entry
here.

The generated table is plain Lua so the host's `require('xi.mapdata')` can load it:

    return {
        [100] = { dat = 5313, scale = 0.1, ox = 155.94, oy = 123.797 },  -- west_ronfaure
        ...
    }
"""
import argparse
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "host", "addons", "lua", "mapdata.lua")

# Zone names are not needed by the HUD, but a comment per row makes the file reviewable.
# The names come from the Atlas zone table when it is passed in.
ZONE_NAMES = {}  # filled from --zones when given


def first_floor(floors):
    """The lowest floor key of a plugin entry ('0', '1', '15' ...)."""
    keys = sorted(floors, key=lambda k: int(k))
    return keys[0] if keys else None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--maps", required=True, help="the Minimap plugin's maps.json (zone -> floor -> dat/map)")
    ap.add_argument("--atlas", required=True, help="FFXI Atlas data/zonesWithMaps.json (zone -> maps[] with scale/offset)")
    ap.add_argument("--zones", help="FFXI Atlas data/zones.json (zone id -> name, for comments)")
    ap.add_argument("--out", default=OUT)
    args = ap.parse_args()

    with open(args.maps, encoding="utf-8") as f:
        maps = json.load(f)
    with open(args.atlas, encoding="utf-8") as f:
        atlas = json.load(f)
    if args.zones:
        with open(args.zones, encoding="utf-8") as f:
            ZONE_NAMES.update({int(k): v for k, v in json.load(f).items()})

    rows = []
    missing = 0
    for zone_key in sorted(maps, key=lambda z: int(z)):
        zone = int(zone_key)
        floors = maps[zone_key]
        if not isinstance(floors, dict) or not floors:
            continue
        floor = first_floor(floors)
        entry = floors[floor]
        dat = entry.get("dat")
        if not dat:
            continue
        place = atlas.get(zone_key)
        if not isinstance(place, dict) or not place.get("maps"):
            missing += 1
            continue
        first = place["maps"][0]
        scale = first.get("scale")
        ox = first.get("offsetX")
        oy = first.get("offsetY")
        if not scale or ox is None or oy is None:
            missing += 1
            continue
        rows.append((zone, int(dat), float(scale), float(ox), float(oy)))

    lines = [
        "--[[",
        "The Battle HUD's zone -> map table.  Generated by tools/gen_map_data.py; do not edit.",
        "",
        "A row is { dat = the map DAT's file id, scale/ox/oy = the map's placement }: a world",
        "position (x, y) is the texel",
        "",
        "    px = (ox + scale * x) / 256 * imageWidth",
        "    py = (oy - scale * y) / 256 * imageHeight",
        "",
        "with the image already top-down (res_map_rgba flips the DAT's rows).  Only the first floor",
        "of a zone is listed; the HUD draws the plain camp radar in zones without a row.  Provenance",
        "and licences: THIRD_PARTY_NOTICES.md.",
        "]]",
        "",
        "return {",
    ]
    for zone, dat, scale, ox, oy in rows:
        name = ZONE_NAMES.get(zone, "")
        comment = ("  -- " + name) if name else ""
        lines.append("    [%d] = { dat = %d, scale = %g, ox = %g, oy = %g },%s" % (zone, dat, scale, ox, oy, comment))
    lines.append("}")
    lines.append("")

    with open(args.out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print("wrote %s: %d zones (%d without placement data)" % (args.out, len(rows), missing))


if __name__ == "__main__":
    sys.exit(main())
