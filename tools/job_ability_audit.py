#!/usr/bin/env python3
"""Classify every row in job_abilities by the code path that handles it.

The three static layers are the status-effect table, the job-point fallback and the
explicit ids compared inside zone.job_ability (plus the Dancer and Corsair tables).
This is deliberately conservative: "effect" or "jpf" means an icon/row exists, not that
the full retail mechanic is implemented.  The per-job deep dives replace those with real
tests.
"""
from __future__ import annotations

import argparse
import re
import sqlite3
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "server"))

from fanxi_server.game import dancer, effects, job_points, rolls  # noqa: E402

JOB_NAMES = {
    1: "WAR", 2: "MNK", 3: "WHM", 4: "BLM", 5: "RDM", 6: "THF",
    7: "PLD", 8: "DRK", 9: "BST", 10: "BRD", 11: "RNG", 12: "SAM",
    13: "NIN", 14: "DRG", 15: "SMN", 16: "BLU", 17: "COR", 18: "PUP",
    19: "DNC", 20: "SCH", 21: "GEO", 22: "RUN", 23: "OTHER",
}


def explicit_ids() -> set[int]:
    text = (ROOT / "server" / "fanxi_server" / "game" / "zone.py").read_text()
    ids: set[int] = set()
    for pattern in (r"ability_id\s*==\s*(\d+)",
                    r"int\(ability_id\)\s*==\s*(\d+)",
                    r"ability_id\s+in\s+\(([^)]*)\)",
                    r"int\(ability_id\)\s+in\s+\(([^)]*)\)"):
        for match in re.finditer(pattern, text):
            for raw in re.findall(r"\d+", match.group(1) if match.groups() else match.group(0)):
                ids.add(int(raw))
    return ids


def classify(ability_id: int, explicit: set[int]) -> str:
    if ability_id in explicit:
        return "system"
    if dancer.is_dancer_ability(ability_id):
        return "system"
    try:
        if rolls.spec(ability_id) is not None:
            return "system"
    except Exception:
        pass
    if ability_id in effects.ABILITY_EFFECTS:
        return "effect"
    try:
        if job_points.ability_effect(ability_id) is not None:
            return "jpf"
    except Exception:
        pass
    return "inert"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--db", default=str(ROOT / "data" / "fanxi.db"))
    parser.add_argument("--out", default="")
    parser.add_argument("--inert", action="store_true", help="only the inert rows")
    args = parser.parse_args()

    db = sqlite3.connect(args.db)
    db.row_factory = sqlite3.Row
    rows = db.execute(
        "SELECT id, name, job, level FROM job_abilities ORDER BY job, level, id").fetchall()
    explicit = explicit_ids()
    per_job: dict[int, list[tuple[sqlite3.Row, str]]] = defaultdict(list)
    counts: dict[int, Counter] = defaultdict(Counter)
    for row in rows:
        status = classify(int(row["id"]), explicit)
        per_job[int(row["job"])].append((row, status))
        counts[int(row["job"])][status] += 1

    lines = ["# Job ability status", "",
             "Generated by `tools/job_ability_audit.py`. `effect` and `jpf` mean an icon",
             "or job-point row exists, not that the full retail mechanic is verified.",
             "", "## Summary", "",
             "| Job | abilities | system | effect | jpf | inert |",
             "|---|---:|---:|---:|---:|---:|"]
    total = Counter()
    for job in sorted(per_job, key=lambda value: (value == 23, value)):
        c = counts[job]
        lines.append("| %s | %d | %d | %d | %d | %d |" % (
            JOB_NAMES.get(job, str(job)), len(per_job[job]),
            c["system"], c["effect"], c["jpf"], c["inert"]))
        total.update(c)
    lines.append("| **total** | **%d** | **%d** | **%d** | **%d** | **%d** |" % (
        sum(total.values()), total["system"], total["effect"], total["jpf"], total["inert"]))
    lines.append("")

    for job in sorted(per_job, key=lambda value: (value == 23, value)):
        lines += ["## " + JOB_NAMES.get(job, str(job)), "",
                  "| id | ability | lvl | status |", "|---:|---|---:|---|"]
        for row, status in per_job[job]:
            if args.inert and status != "inert":
                continue
            lines.append("| %d | %s | %d | %s |" % (
                int(row["id"]), str(row["name"]), int(row["level"]), status))
        lines.append("")

    text = "\n".join(lines)
    if args.out:
        Path(args.out).write_text(text + "\n")
        print("wrote %s" % args.out)
    else:
        print("\n".join(lines[:40]))
    print("abilities: %d  system: %d  effect: %d  jpf: %d  inert: %d" % (
        sum(total.values()), total["system"], total["effect"], total["jpf"], total["inert"]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
