"""Oboro Dynamis-Divergence weapon augments.

Oboro (Port Jeuno E-6) augments the crafted JSE weapons from Dynamis -
Divergence.  The client stores the choice in the same 24-byte
``AugmentBundle`` block Odyssey and Limbus use, so the launcher can cap a path
with the existing ``progress``/``augment`` action.  Every family has three
qualities (NQ R15, HQ1 R20, HQ2 R25) and three paths (A, B, C).

The data lives in ``data/oboro_r25.json`` (generated by
``tools/gen_oboro.py`` from the same table this module reads) so the card, the
docs and the migration cannot drift apart.  Bundle indices are the client's
own augment-table rows; the families are stored in that table's order.
"""

from __future__ import annotations

import json
from pathlib import Path

from . import augments

ROOT = Path(__file__).resolve().parents[3]
PATH = ROOT / "data" / "oboro_r25.json"
_cache: dict | None = None

# FFXI's job order, for a stable select.
JOB_ORDER = {
    name: index for index, name in enumerate((
        "WAR", "MNK", "WHM", "BLM", "RDM", "THF", "PLD", "DRK", "BST", "BRD",
        "RNG", "SAM", "NIN", "DRG", "SMN", "BLU", "COR", "PUP", "DNC", "SCH",
        "GEO", "RUN",
    ), start=1)
}

QUALITY_ORDER = {"nq": 0, "hq1": 1, "hq2": 2}


def data() -> dict:
    global _cache
    if _cache is None:
        try:
            _cache = json.loads(PATH.read_text())
        except (OSError, ValueError):
            _cache = {"weapons": [], "qualities": {}}
    return _cache


def _path(key: str, label: str, bundle: int, quality: dict,
          rows: list[str], total_rp: int) -> dict:
    return {
        "key": key,
        "label": label,
        "bundle": int(bundle),
        "rank": int(quality["rank"]),
        "tier": int(quality["tier"]),
        "rp": int(quality["rp"]),
        "total_rp": int(total_rp),
        "curve": int(data().get("rp_curve", 0)),
        "augments": list(rows),
    }


def entries() -> list[dict]:
    """Every Oboro item, quality included, with its three paths."""
    out: list[dict] = []
    for weapon in data().get("weapons", []):
        ranged = bool(weapon.get("ranged"))
        double = "Chance of double ranged damage" if ranged else "Chance of double damage"
        follow = "Chance of ranged follow-up attack" if ranged else "Chance of follow-up attack"
        for quality_key in ("nq", "hq1", "hq2"):
            tier = weapon.get("tiers", {}).get(quality_key)
            quality = data().get("qualities", {}).get(quality_key)
            if not tier or not quality:
                continue
            bundles = tier["bundles"]
            a_rows = [
                "%s +%d%%" % (double, int(quality["double_damage"])),
                '"Store TP"+%d' % int(quality["store_tp"]),
            ]
            b_rows = [
                "%s +%d%%" % (follow, int(quality["follow_up"])),
                '"Subtle Blow II"+%d' % int(quality["subtle_blow_ii"]),
            ]
            if quality_key == "hq2":
                a_rows.append("DMG:+%d" % int(weapon["dmg"]))
                b_rows.append("DMG:+%d" % int(weapon["dmg"]))
            out.append({
                "item_id": int(tier["item_id"]),
                "name": tier["name"],
                "slot": weapon.get("slot") or "",
                "set": "Oboro JSE weapon",
                "kind": "oboro",
                "job": weapon.get("job") or "",
                "weapon": weapon.get("weapon") or "",
                "quality": quality["label"],
                "quality_key": quality_key,
                "rank": int(quality["rank"]),
                "tier": int(quality["tier"]),
                "rp": int(quality["rp"]),
                "total_rp": int(quality["total_rp"]),
                "curve": int(data().get("rp_curve", 0)),
                "paths": [
                    _path("A", "Path A", bundles["A"], quality, a_rows,
                          quality["total_rp"]),
                    _path("B", "Path B", bundles["B"], quality, b_rows,
                          quality["total_rp"]),
                    _path("C", "Path C", bundles["C"], quality, tier["c"],
                          quality["total_rp"]),
                ],
            })
    return out


def get(item_id: int) -> dict | None:
    want = int(item_id)
    return next((entry for entry in entries() if int(entry["item_id"]) == want), None)


def find(query: str) -> list[dict]:
    want = " ".join(str(query or "").split()).casefold()
    if not want:
        return []
    return [entry for entry in entries() if want in entry["name"].casefold()]


def rows() -> set[str]:
    """Every augment line the dataset can show (for the coverage test)."""
    out: set[str] = set()
    for entry in entries():
        for path in entry["paths"]:
            out.update(path["augments"])
    return out


def catalog(service, character_id: int) -> dict:
    """Every Oboro item with the character's copies and current blocks.

    Owned items come first so the card opens on something the character can
    actually cap; an item with no copy carries ``owned`` false and can be
    bought through the Armory action from the same card.
    """
    items = entries()
    ids = [int(entry["item_id"]) for entry in items]
    if not ids:
        return {"source": data().get("source", ""), "note": data().get("note", ""),
                "max_rank": 25, "items": []}

    prices: dict[int, int] = {}
    if ids:
        placeholders = ",".join("?" for _ in ids)
        for row in service.db.all(
                "SELECT item_id, price FROM items WHERE item_id IN (%s)" % placeholders,
                tuple(ids)):
            prices[int(row["item_id"])] = int(row["price"] or 0)

    copies: dict[int, list[dict]] = {}
    wanted = set(ids)
    for row in service.inventory(int(character_id)):
        item_id = int(row["item_id"])
        if item_id not in wanted:
            continue
        copies.setdefault(item_id, []).append({
            "container": int(row["container"]),
            "slot": int(row["slot"]),
            "current": augments.decode(row.get("extra")),
        })

    out = []
    for entry in items:
        owned_copies = sorted(copies.get(int(entry["item_id"]), []),
                              key=lambda copy: (copy["container"], copy["slot"]))
        out.append(dict(
            entry,
            price=prices.get(int(entry["item_id"]), 0),
            owned=bool(owned_copies),
            copies=owned_copies,
        ))
    out.sort(key=lambda entry: (
        0 if entry["owned"] else 1,
        JOB_ORDER.get(entry.get("job"), 99),
        -QUALITY_ORDER.get(entry.get("quality_key"), 0),
        entry["name"].casefold(),
    ))
    return {
        "source": data().get("source", ""),
        "note": data().get("note", ""),
        "max_rank": max((int(entry["rank"]) for entry in items), default=25),
        "items": out,
    }
